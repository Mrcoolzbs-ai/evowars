/** Спецификация одного нуклида-кандидата (данные NUBASE2020). */
interface NuclideSpec {
  /** Массовое число A — целое число нуклонов (НЕ атомная масса). */
  a: number;
  /** Основное или изомерное состояние (сравниваются отдельно). */
  state: 'ground' | 'isomeric';
  /**
   * Индекс состояния i из NUBASE2020: 0 — основное состояние,
   * 1 — изомер в текущих данных (все 3 изомера-кандидата —
   * строки i=1, s=m). Пара (i, s) идентифицирует конкретную
   * строку источника (аудит R2).
   */
  i: number;
  /** Буквенный код состояния s из NUBASE2020 ('' у основного состояния). */
  s: string;
  /** Период полураспада в единице реестра проекта. */
  value: number;
  /** 1 сигма в той же единице; null — неопределённость не опубликована. */
  sigma: number | null;
  /** Единица времени реестра (y/ky/My/yr/ka/Ma/day/h/min/s/ms). */
  unit: string;
  /** Исходная нотация NUBASE2020 (значение, скобки, единица). */
  raw: string;
  /** Режимы распада — дословно из столбца BR NUBASE2020. */
  decay: string;
  /** Причина включения в список кандидатов. */
  reason: string;
  /** Звёздочка NUBASE (*): порядок основного/изомерного состояния не установлен. */
  orderingUncertain?: boolean;
}

/** Спецификация кандидатов одного элемента. */
interface ElementCandidatesSpec {
  z: number;
  completeness: 'complete' | 'not_verifiable' | 'incomplete';
  completenessNote: string;
  candidates: readonly NuclideSpec[];
}

